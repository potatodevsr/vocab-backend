// Compile data/thai-letters.mjs into the ThaiLetter migration.
//
//   node scripts/generate-thai-letter-seed.mjs > migrations/0011_thai_letter.sql
//
// The content ships *in the migration* rather than in seed/e2e.sql because it is the same
// in every environment and never varies by fixture: dev, e2e and production all apply
// migrations, so one file gets the alphabet everywhere with no seeding step to forget.
// It also means `/admin/letters` edits survive — a migration runs once, a seed re-runs.
//
// Regenerate only while the migration is still unapplied anywhere. Once it has run, a
// wording change is an admin edit or a new migration, never a rewrite of this file's
// output: wrangler tracks migrations by name and will not re-apply an edited one.

import { THAI_LETTERS, THAI_LETTER_COUNTS } from "../data/thai-letters.mjs";

const sql = (value) => `'${String(value).replace(/'/g, "''")}'`;

// Fixed, not `new Date()`: the output must be byte-identical between regenerations, the
// same property `generate-e2e-seed.mjs` relies on.
const STAMP = "2026-01-01T00:00:00.000Z";

const lines = [
    "-- The Thai writing system as curated content (see backend/data/thai-letters.mjs).",
    "--",
    `-- ${THAI_LETTER_COUNTS.consonant} consonants, ${THAI_LETTER_COUNTS.vowelSign} written vowel signs,`,
    `-- ${THAI_LETTER_COUNTS.tone} tone marks and the traditional ${THAI_LETTER_COUNTS.vowelSound} vowel sounds.`,
    "--",
    "-- Generated by scripts/generate-thai-letter-seed.mjs — do not hand-edit. A wording change",
    "-- after this has been applied is an admin edit through /admin/letters, or a new migration.",
    "",
    'CREATE TABLE "ThaiLetter" (',
    '    "id" TEXT NOT NULL PRIMARY KEY,',
    '    "kind" TEXT NOT NULL,',
    '    "ordinal" INTEGER NOT NULL,',
    '    "char" TEXT NOT NULL,',
    '    "name" TEXT NOT NULL,',
    '    "roman" TEXT NOT NULL DEFAULT \'\',',
    '    "sound" TEXT NOT NULL DEFAULT \'\',',
    '    "soundFinal" TEXT NOT NULL DEFAULT \'\',',
    '    "vowelLength" TEXT NOT NULL DEFAULT \'\',',
    '    "clip" TEXT NOT NULL DEFAULT \'\',',
    '    "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,',
    '    "updatedAt" DATETIME NOT NULL',
    ");",
    "",
    'CREATE UNIQUE INDEX "ThaiLetter_kind_char_key" ON "ThaiLetter"("kind", "char");',
    'CREATE INDEX "ThaiLetter_kind_ordinal_idx" ON "ThaiLetter"("kind", "ordinal");',
    "",
];

for (const letter of THAI_LETTERS) {
    lines.push(
        'INSERT INTO "ThaiLetter" (id, kind, ordinal, char, name, roman, sound, soundFinal, vowelLength, clip, createdAt, updatedAt) VALUES (' +
            [
                sql(letter.id),
                sql(letter.kind),
                letter.ordinal,
                sql(letter.char),
                sql(letter.name),
                sql(letter.roman),
                sql(letter.sound),
                sql(letter.soundFinal),
                sql(letter.vowelLength),
                // The audio key defaults to the id — they were the same string before this
                // table existed, so every clip already in R2 keeps resolving.
                sql(letter.id),
                sql(STAMP),
                sql(STAMP),
            ].join(", ") +
            ");",
    );
}

lines.push("");

process.stdout.write(lines.join("\n"));
